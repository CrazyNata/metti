const commonSkillIds = [
  "wardrobe_grounding",
  "outfit_architecture",
  "visual_styling",
  "context_fit",
  "explainable_advice",
  "quality_gate",
] as const satisfies readonly StylistSkillId[];

const modeSkillIds: Readonly<Record<StylistMode, readonly StylistSkillId[]>> = {
  today: ["wear_rotation", "variant_diversity"],
  selected_item: ["selected_anchor", "variant_diversity"],
  restyle: ["locked_restyle", "variant_diversity"],
  packing: ["capsule_planning", "wear_rotation", "variant_diversity"],
  shopping_recommendation: ["shopping_gap_analysis", "capsule_planning"],
};

export function buildStylistSkillPrompt(mode: StylistMode): string {
  const ids = [...new Set([...commonSkillIds, ...modeSkillIds[mode]])];
  return [
    `# Metti stylist skills v${STYLIST_SKILLS_VERSION}`,
    "Применяй активные skills как внутренний чек-лист. Не выводи названия skills пользователю и не добавляй для них отдельные поля.",
    STYLIST_VOCABULARY_PROMPT,
    ...ids.map((id) => `## ${id}\n${STYLIST_SKILLS[id]}`),
  ].join("\n\n");
}

